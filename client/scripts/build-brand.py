"""Build brand geometry from the owner's Illustrator logo (src/assets/brand/logo-full.svg).

Outputs (all single-colour, currentColor-driven; nothing is retyped in a font):
  src/components/brand/brandPaths.js  - path data + layouts for BrandMark / BrandLogo / BrandLockup / Edelweiss
  public/favicon.svg                  - crescent + edelweiss mark, #5C000E (white in dark browser UI)
  public/brand/mark.svg               - same mark, #5C000E, for anything outside React
Then run `node scripts/build-icons.mjs` to rasterise the PNG icon sizes.

Path order in the source SVG: 0 = crescent, 1 = edelweiss, 2-6 = C A H A N, 7-13 = A C A D E M Y.
Requires: pip install svgelements
"""
import json
import os
import re

from svgelements import Path

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SRC = os.path.join(ROOT, "src", "assets", "brand", "logo-full.svg")

svg = open(SRC, encoding="utf-8").read()
paths = [re.sub(r"\s+", " ", d).strip() for d in re.findall(r'<path[^>]*d="([^"]+)"', svg, re.S)]
assert len(paths) == 14, len(paths)
boxes = [tuple(float(v) for v in Path(d).bbox()) for d in paths]

CRESCENT, FLOWER = paths[0], paths[1]
CAHAN = list(range(2, 7))
ACADEMY = list(range(7, 14))


def union(idx):
    xs0, ys0, xs1, ys1 = zip(*(boxes[i] for i in idx))
    return min(xs0), min(ys0), max(xs1), max(ys1)


def r(v):
    return round(v, 2)


mx0, my0, mx1, my1 = union([0, 1])
mark_w, mark_h = mx1 - mx0, my1 - my0

# ---- mark (crescent + edelweiss), tight viewBox with a hair of padding
PAD = 4
mark = {
    "viewBox": f"{r(mx0 - PAD)} {r(my0 - PAD)} {r(mark_w + 2 * PAD)} {r(mark_h + 2 * PAD)}",
    "paths": [{"d": CRESCENT}, {"d": FLOWER}],
}

# ---- stacked logo, cropped to content
sx0, sy0, sx1, sy1 = union(range(14))
stacked = {
    "viewBox": f"{r(sx0 - PAD)} {r(sy0 - PAD)} {r(sx1 - sx0 + 2 * PAD)} {r(sy1 - sy0 + 2 * PAD)}",
    "paths": [{"d": d} for d in paths],
}

# ---- horizontal lockup: mark left, CAHAN over a tracked ACADEMY on the right
CAHAN_K = 1.3
ACAD_K = 2.6
GAP_X = 80
GAP_Y = 44
cx0, cy0, cx1, cy1 = union(CAHAN)
cahan_w, cahan_h = (cx1 - cx0) * CAHAN_K, (cy1 - cy0) * CAHAN_K
ax0, ay0, ax1, ay1 = union(ACADEMY)
acad_h = (ay1 - ay0) * ACAD_K
block_h = cahan_h + GAP_Y + acad_h
top = (mark_h - block_h) / 2
left = mark_w + GAP_X
lock_paths = [
    {"d": CRESCENT, "transform": f"translate({r(-mx0)} {r(-my0)})"},
    {"d": FLOWER, "transform": f"translate({r(-mx0)} {r(-my0)})"},
]
for i in CAHAN:
    lock_paths.append({
        "d": paths[i],
        "transform": f"translate({r(left)} {r(top)}) scale({CAHAN_K}) translate({r(-cx0)} {r(-cy0)})",
    })
letter_ws = [(boxes[i][2] - boxes[i][0]) * ACAD_K for i in ACADEMY]
gap = (cahan_w - sum(letter_ws)) / (len(ACADEMY) - 1)
x = left
acad_top = top + cahan_h + GAP_Y
for i, w in zip(ACADEMY, letter_ws):
    bx0, by0 = boxes[i][0], ay0  # shared baseline box so letters stay aligned
    lock_paths.append({
        "d": paths[i],
        "transform": f"translate({r(x)} {r(acad_top)}) scale({ACAD_K}) translate({r(-bx0)} {r(-by0)})",
    })
    x += w + gap
lock_w = left + cahan_w
lockup = {"viewBox": f"{-PAD} {-PAD} {r(lock_w + 2 * PAD)} {r(mark_h + 2 * PAD)}", "paths": lock_paths}

# ---- edelweiss alone (the logo's own line-art flower)
fx0, fy0, fx1, fy1 = boxes[1]
edelweiss = {
    "viewBox": f"{r(fx0 - PAD)} {r(fy0 - PAD)} {r(fx1 - fx0 + 2 * PAD)} {r(fy1 - fy0 + 2 * PAD)}",
    "paths": [{"d": FLOWER}],
}

out = os.path.join(ROOT, "src", "components", "brand", "brandPaths.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/build-brand.py from src/assets/brand/logo-full.svg. Do not edit by hand.\n")
    f.write("// P holds each source path once; layouts reference it by index to keep the bundle small.\n")
    f.write(f"const P = {json.dumps(paths, indent=2)};\n")

    def ref(obj):
        items = []
        for p in obj["paths"]:
            i = paths.index(p["d"])
            tr = f", transform: {json.dumps(p['transform'])}" if p.get("transform") else ""
            items.append(f"    {{ d: P[{i}]{tr} }}")
        return "{\n  viewBox: " + json.dumps(obj["viewBox"]) + ",\n  paths: [\n" + ",\n".join(items) + ",\n  ],\n}"

    for name, obj in (("MARK", mark), ("STACKED", stacked), ("LOCKUP", lockup), ("EDELWEISS", edelweiss)):
        f.write(f"export const {name} = {ref(obj)};\n")
print("wrote", out)

# ---- favicon: square, centred mark
side = max(mark_w, mark_h) + 40
cx, cy = (mx0 + mx1) / 2, (my0 + my1) / 2
vb = f"{r(cx - side / 2)} {r(cy - side / 2)} {r(side)} {r(side)}"
fav = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}">'
    "<style>path{fill:#5C000E}@media (prefers-color-scheme:dark){path{fill:#FFFFFF}}</style>"
    f'<path d="{CRESCENT}"/><path d="{FLOWER}"/></svg>\n'
)
open(os.path.join(ROOT, "public", "favicon.svg"), "w", encoding="utf-8", newline="\n").write(fav)
os.makedirs(os.path.join(ROOT, "public", "brand"), exist_ok=True)
plain = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" fill="#5C000E">'
    f'<path d="{CRESCENT}"/><path d="{FLOWER}"/></svg>\n'
)
open(os.path.join(ROOT, "public", "brand", "mark.svg"), "w", encoding="utf-8", newline="\n").write(plain)
plain_white = plain.replace('fill="#5C000E"', 'fill="#FFFFFF"')
open(os.path.join(ROOT, "public", "brand", "mark-white.svg"), "w", encoding="utf-8", newline="\n").write(plain_white)
stacked_svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{stacked["viewBox"]}" fill="#5C000E">'
    + "".join(f'<path d="{d}"/>' for d in paths)
    + "</svg>\n"
)
# legacy path still referenced by pages that are not migrated yet (they invert it in dark mode)
open(os.path.join(ROOT, "public", "cahan-logo.svg"), "w", encoding="utf-8", newline="\n").write(stacked_svg)
print("wrote favicon.svg, brand/mark.svg, brand/mark-white.svg, cahan-logo.svg")
